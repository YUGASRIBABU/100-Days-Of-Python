# Day 9: Basic Math For Loop Practice
number = [2, 4, 6, 8]

print("Starting our for loop Math Challenge!")
print("-" * 40)

for num in number:
    squared = num ** 2
    tripled = num * 3

    print(f"Original Number: {num}")
    print(f"-> Squared = {squared}")
    print(f"-> Tripled = {tripled}")
    print("-" * 40)
